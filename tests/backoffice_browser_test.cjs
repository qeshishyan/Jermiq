const fs=require('fs');
const path=require('path');
const {createRequire}=require('module');
const req=createRequire(process.env.JERMIQ_BROWSER_MODULE_ROOT ? path.join(process.env.JERMIQ_BROWSER_MODULE_ROOT,'package.json') : __filename);
const {chromium}=req('playwright');
const chromiumPackage=req('@sparticuz/chromium');
const packaged=chromiumPackage.default || chromiumPackage;
const output=path.join(__dirname,'../test-results');
(async()=>{
 const input=JSON.parse(fs.readFileSync(0,'utf8'));
 const browser=await chromium.launch({headless:true,executablePath:await packaged.executablePath(),args:packaged.args});
 const context=await browser.newContext({viewport:{width:1440,height:1050}});
 await context.addCookies(input.cookie.split('; ').map(x=>{const at=x.indexOf('=');return {name:x.slice(0,at),value:x.slice(at+1),url:input.baseUrl};}));
 const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 fs.mkdirSync(output,{recursive:true});
 await page.goto(input.baseUrl+'/admin?lang=hy');await page.locator('.office-stat').first().waitFor();
 await page.locator('#lead-new').click();await page.locator('#lead-form').waitFor({state:'visible'});
 await page.screenshot({path:path.join(output,'office-desktop.png'),fullPage:false});
 const desktopOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
 if(desktopOverflow)throw Error('Desktop workspace overflows');
 await page.locator('[data-tab="translations"]').click();await page.locator('.translation-row').first().waitFor();
 await page.screenshot({path:path.join(output,'cms-translations.png'),fullPage:false});
 await page.setViewportSize({width:390,height:844});await page.locator('[data-tab="leads"]').click();
 await page.screenshot({path:path.join(output,'office-mobile.png'),fullPage:false});
 const mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
 if(mobileOverflow)throw Error('Mobile workspace overflows');
 await page.goto(input.baseUrl+'/?lang=ru');await page.locator('.hero').waitFor();
 await page.screenshot({path:path.join(output,'site-russian-mobile.png'),fullPage:false});
 const publicOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
 if(publicOverflow)throw Error('Mobile public site overflows');
 await page.setViewportSize({width:1440,height:1050});await page.goto(input.baseUrl+'/?lang=en');
 await page.screenshot({path:path.join(output,'site-english-desktop.png'),fullPage:false});
 if(errors.length)throw Error(errors.join('\n'));
 console.log(JSON.stringify({browserPassed:5,screenshots:5,consoleErrors:0,desktopOverflow:false,mobileOverflow:false}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
